export type Country = { name: string; dial: string; continent: Continent };

export const countries: Country[] = DATA.split("\n").map((line) => {
  const [name, dial, continent] = line.split("|");
  return { name, dial: `+${dial}`, continent: CONTINENTS[continent] };
});

export const countryNames = countries.map((c) => c.name);

const byName = new Map(countries.map((c) => [c.name, c]));

export function findCountry(name: string) {
  return byName.get(name);
}

/** Phone-code choices, e.g. "Kenya (+254)". The value is the country name, since codes like +1 are shared. */
export const dialOptions = countries.map((c) => ({ value: c.name, label: `${c.name} (${c.dial})` }));
